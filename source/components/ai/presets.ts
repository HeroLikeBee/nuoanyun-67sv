/** 取某页的上下文问题；未配置的页面返回空数组（界面回落为「按分类浏览」） */
export function hintsFor(page: string): AiPreset[] {
  const ids = PAGE_HINTS[page] ?? [];
  return ids
    .map((id) => AI_PRESETS.find((p) => p.id === id))
    .filter((p): p is AiPreset => !!p);
}

/** 关键词命中打分：命中越多越靠前；同分取更短的问题（更贴近用户原话） */
export function matchPreset(input: string): AiPreset | null {
  const s = input.trim().toLowerCase();
  if (!s) return null;
  let bestP: AiPreset | null = null;
  let bestScore = 0;
  AI_PRESETS.forEach((p) => {
    let score = 0;
    p.kw.forEach((k) => { if (s.includes(k.toLowerCase())) score += k.length >= 2 ? 2 : 1; });
    if (s.includes(p.q.toLowerCase())) score += 6;
    if (score > bestScore) { bestScore = score; bestP = p; }
  });
  return bestP;
}
